/**
 * Listing ages are relative to process start so the catalogue always reads
 * as freshly traded, rather than drifting into the past.
 */
const CATALOGUE_EPOCH = Date.now();
const DAY_MS = 86_400_000;

function isoDaysAgo(days: number): string {
  return new Date(CATALOGUE_EPOCH - days * DAY_MS).toISOString();
}

function buildImages(slugs: string[], title: string): VehicleImage[] {
  return slugs.map((slug, index) => {
    const entry = imageManifest[slug];
    if (!entry) {
      throw new Error(`Missing image manifest entry for "${slug}"`);
    }
    return {
      url: `/images/vehicles/${slug}.jpg`,
      alt:
        index === 0
          ? `${title} — front three-quarter view`
          : `${title} — photo ${index + 1}`,
      width: entry.width,
      height: entry.height,
      blurDataURL: entry.blurDataURL,
      credit: imageCredits[slug],
    };
  });
}

function resolveSeller(slug: string): Seller {
  const seller = allSellers.find((s) => s.slug === slug);
  if (!seller) throw new Error(`Unknown seller slug: ${slug}`);
  return seller;
}

function toVehicle(seed: VehicleSeed): Vehicle {
  const brand = getBrandBySlug(seed.brand);
  if (!brand) throw new Error(`Unknown brand slug: ${seed.brand}`);

  const category = getCategoryById(seed.category);
  if (!category) throw new Error(`Unknown category: ${seed.category}`);

  const title = [seed.year, brand.name, seed.model, seed.variant]
    .filter(Boolean)
    .join(" ");

  const createdAt = isoDaysAgo(seed.daysAgo);

  return {
    id: seed.id,
    slug: buildVehicleSlug({
      brand: brand.slug,
      model: seed.model,
      variant: seed.variant,
      year: seed.year,
      city: seed.city,
      id: seed.id,
    }),
    title,
    category,
    brand,
    model: seed.model,
    variant: seed.variant,
    manufacturingYear: seed.year,
    registrationYear: seed.registrationYear,
    registrationNumber: seed.registrationNumber,
    price: seed.price,
    previousPrice: seed.previousPrice,
    negotiable: seed.negotiable ?? true,
    fuelType: seed.fuelType,
    transmission: seed.transmission,
    kilometers: seed.kilometers,
    ownershipCount: seed.ownershipCount,
    condition: seed.condition,
    specifications: seed.specifications,
    highlights: seed.highlights,
    description: seed.description,
    location: locationOf(seed.city, seed.region, seed.pincode),
    images: buildImages(seed.images, title),
    seller: resolveSeller(seed.sellerSlug),
    verification: {
      isVerified: false,
      rcAvailable: false,
      insuranceValid: false,
      fitnessValid: false,
      permitValid: false,
      inspected: false,
      ...seed.verification,
      inspectedAt: seed.verification.inspected
        ? isoDaysAgo(seed.daysAgo + 2)
        : undefined,
    },
    status: seed.status ?? "available",
    featured: seed.featured ?? false,
    viewCount: seed.viewCount,
    createdAt,
    updatedAt: isoDaysAgo(Math.max(0, seed.daysAgo - 1)),
  };
}

export const mockVehicles: Vehicle[] = seeds.map(toVehicle);
