const strip = (html) =>
  String(html ?? "")
    .replace(/<[^>]*>/g, "")
    .replace(/\s+/g, " ")
    .replace(/"/g, "'")
    .trim();

const titles = Object.values(SOURCE_FILES).map((f) => `File:${f}`);
const meta = {};

// The API takes up to 50 titles per request.
for (let i = 0; i < titles.length; i += 20) {
  const batch = titles.slice(i, i + 20).join("|");
  const url =
    "https://commons.wikimedia.org/w/api.php?action=query&format=json" +
    "&prop=imageinfo&iiprop=extmetadata&titles=" +
    encodeURIComponent(batch);
  const json = JSON.parse(
    execFileSync("curl", ["-sL", "--max-time", "60", "-A", UA, url], {
      maxBuffer: 1 << 26,
    }).toString(),
  );
  for (const page of Object.values(json?.query?.pages ?? {})) {
    const md = page.imageinfo?.[0]?.extmetadata;
    if (!md) continue;
    meta[page.title] = {
      author: strip(md.Artist?.value) || "Wikimedia Commons contributor",
      license: strip(md.LicenseShortName?.value) || "See source",
    };
  }
}

const entries = Object.entries(SOURCE_FILES)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([slug, file]) => {
    const found = meta[`File:${file}`] ?? {
      author: "Wikimedia Commons contributor",
      license: "See source",
    };
    const source = `https://commons.wikimedia.org/wiki/${encodeURIComponent(
      `File:${file}`.replace(/ /g, "_"),
    )}`;
    return `  "${slug}": {\n    author: "${found.author}",\n    license: "${found.license}",\n    source: "${source}",\n  },`;
  });

writeFileSync(
  "data/image-credits.ts",
  `/**\n * Auto-generated by scripts/generate-image-credits.mjs — do not edit by hand.\n *\n * Attribution for the openly licensed stand-in catalogue photography.\n * Replace these images (and this file) with real listing photos before\n * launch; see README "Catalogue imagery".\n */\nimport type { VehicleImage } from "@/types/vehicle";\n\nexport const imageCredits: Record<string, NonNullable<VehicleImage["credit"]>> = {\n${entries.join("\n")}\n};\n`,
);

